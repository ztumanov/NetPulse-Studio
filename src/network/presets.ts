export function createDefaultServices(type: DeviceType): ServerServices {
  return {
    dhcpEnabled: type === 'router' || type === 'server',
    dhcpPools: [],
    dhcpLeases: [],
    dnsEnabled: type === 'server',
    dnsRecords: [
      { id: 'dns-1', domain: 'app.corp.local', ipAddress: '192.168.2.100' },
      { id: 'dns-2', domain: 'portal.netpulse.lan', ipAddress: '192.168.2.100' },
      { id: 'dns-3', domain: 'gateway.corp.local', ipAddress: '192.168.1.1' },
    ],
    httpEnabled: type === 'server',
    httpTitle: 'NetPulse Corporate Intranet Portal (HTTP/1.1 200 OK)',
    httpBody:
      'Добро пожаловать на веб-сервер SRV-Web! DNS-разрешение имени, TCP 3-Way Handshake (SYN / SYN-ACK / ACK) и передача HTTP GET успешно выполнены.',
  };
}

export function createDeviceNode(
  type: DeviceType,
  index: number,
  x: number,
  y: number,
  customName?: string,
  switchPortCount: number = 6
): NetworkNode {
  const cleanSwitchPorts = type === 'switch' ? Math.max(2, switchPortCount) : 6;
  const prefix =
    type === 'router'
      ? 'RTR'
      : type === 'switch'
      ? cleanSwitchPorts >= 24
        ? 'SW24'
        : 'SW'
      : type === 'server'
      ? 'SRV'
      : 'PC';
  const name = customName || `${prefix}-${index}`;
  const id = `${type}-${Date.now()}-${index}`;

  const interfaces =
    type === 'router'
      ? [
          {
            id: `${id}-fa0/0`,
            name: 'FastEthernet0/0',
            shortName: 'Fa0/0',
            macAddress: generateMacAddress(index, 1),
            ipAddress: '',
            subnetMask: '255.255.255.0',
            adminStatus: 'up' as const,
            vlanMode: 'access' as const,
            accessVlan: 1,
            trunkAllowedVlans: [1, 10, 20, 30],
          },
          {
            id: `${id}-fa0/1`,
            name: 'FastEthernet0/1',
            shortName: 'Fa0/1',
            macAddress: generateMacAddress(index, 2),
            ipAddress: '',
            subnetMask: '255.255.255.0',
            adminStatus: 'up' as const,
            vlanMode: 'access' as const,
            accessVlan: 1,
            trunkAllowedVlans: [1, 10, 20, 30],
          },
          {
            id: `${id}-gi0/0`,
            name: 'GigabitEthernet0/0',
            shortName: 'Gi0/0',
            macAddress: generateMacAddress(index, 3),
            ipAddress: '',
            subnetMask: '255.255.255.0',
            adminStatus: 'up' as const,
            vlanMode: 'access' as const,
            accessVlan: 1,
            trunkAllowedVlans: [1, 10, 20, 30],
          },
        ]
      : type === 'switch'
      ? [
          ...Array.from({ length: cleanSwitchPorts }, (_, i) => {
            const portNum = i + 1;
            return {
              id: `${id}-fa0/${portNum}`,
              name: `FastEthernet0/${portNum}`,
              shortName: `Fa0/${portNum}`,
              macAddress: generateMacAddress(index, portNum),
              ipAddress: '',
              subnetMask: '',
              adminStatus: 'up' as const,
              vlanMode: 'access' as const,
              accessVlan: 1,
              trunkAllowedVlans: [1, 10, 20, 30],
            };
          }),
          {
            id: `${id}-gi0/1`,
            name: 'GigabitEthernet0/1',
            shortName: 'Gi0/1',
            macAddress: generateMacAddress(index, cleanSwitchPorts + 1),
            ipAddress: '',
            subnetMask: '',
            adminStatus: 'up' as const,
            vlanMode: 'trunk' as const,
            accessVlan: 1,
            trunkAllowedVlans: [1, 10, 20, 30],
          },
          {
            id: `${id}-gi0/2`,
            name: 'GigabitEthernet0/2',
            shortName: 'Gi0/2',
            macAddress: generateMacAddress(index, cleanSwitchPorts + 2),
            ipAddress: '',
            subnetMask: '',
            adminStatus: 'up' as const,
            vlanMode: 'trunk' as const,
            accessVlan: 1,
            trunkAllowedVlans: [1, 10, 20, 30],
          },
        ]
      : [
          {
            id: `${id}-eth0`,
            name: 'Ethernet0',
            shortName: 'Eth0',
            macAddress: generateMacAddress(index, 1),
            ipAddress: '',
            subnetMask: '255.255.255.0',
            adminStatus: 'up' as const,
            vlanMode: 'access' as const,
            accessVlan: 1,
            trunkAllowedVlans: [1],
          },
        ];

  return {
    id,
    name,
    type,
    x,
    y,
    defaultGateway: '',
    dnsServer: '192.168.2.100',
    ipAssignmentMode: 'static',
    services: createDefaultServices(type),
    interfaces,
    routingTable: [],
    arpTable: [],
    macTable: [],
    cli: {
      mode: 'user',
      history: [
        `Cisco IOS Software, NetPulse Simulation OS, Version 15.4(3)M, RELEASE SOFTWARE`,
        `System image file is "flash:netpulse-advipservicesk9-mz.bin"`,
        `Введите "?" или "help" для справки по командам (включая ping, traceroute, ipconfig /renew).`,
      ],
    },
  };
}

